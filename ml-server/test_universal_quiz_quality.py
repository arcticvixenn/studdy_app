def call_api(payload):
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")

    request = urllib.request.Request(
        "http://127.0.0.1:6060/quiz/generate",
        data=data,
        headers={"Content-Type": "application/json; charset=utf-8"},
        method="POST",
    )

    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


all_results = {}

for case in TEST_CASES:
    print("\n" + "=" * 90)
    print(case["title"])
    print("=" * 90)

    result = call_api(case)
    all_results[case["title"]] = result

    questions = result.get("questions", [])
    print("Питань:", len(questions))

    for index, question in enumerate(questions, start=1):
        print(f"\n{index}. {question.get('questionText')}")
        print(f"A: {question.get('optionA')}")
        print(f"B: {question.get('optionB')}")
